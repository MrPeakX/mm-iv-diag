#!/usr/bin/env perl
# SPDX-License-Identifier: MIT
# tools/mkversion.pl -- generate the ca65 version include from VERSION and
# RELEASE_DATE.
#
# Usage: mkversion.pl VERSION_FILE RELEASE_DATE_FILE OUTPUT_FILE
#
# The embedded timestamp is the release date from RELEASE_DATE_FILE (one
# line "YYYY-MM-DD HH:MM:SS", UTC), so every build of a release is
# bit-identical. It never depends on the current time; SOURCE_DATE_EPOCH,
# if set, overrides it explicitly. OUTPUT_FILE is only rewritten when its
# content changes.

use v5.40;
use POSIX ();
use Time::Local ();

die "usage: $0 VERSION_FILE RELEASE_DATE_FILE OUTPUT_FILE\n" unless @ARGV == 3;
my ($version_file, $date_file, $out_file) = @ARGV;

sub first_line($path) {
  open(my $in, '<', $path) or die "$path: $!\n";
  my $line = <$in> // '';
  close($in);
  $line =~ s/\s+\z//;
  return $line;
}

my $version = first_line($version_file);

# Semantic version, optional pre-release; must fit IDENT_VSTRING_LEN - 1
# (include/ident.inc).
my ($major, $minor, $patch) =
  $version =~ /\A(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(?:-[0-9A-Za-z.-]+)?\z/
  or die "$version_file: '$version' is not a semantic version\n";
die "$version_file: '$version' is longer than 11 characters\n" if length($version) > 11;
for my $n ($major, $minor, $patch) {
  die "$version_file: version component $n exceeds 255\n" if $n > 255;
}

my $timestamp;
if (defined $ENV{SOURCE_DATE_EPOCH}) {
  my $epoch = $ENV{SOURCE_DATE_EPOCH};
  die "SOURCE_DATE_EPOCH must be an integer\n" unless $epoch =~ /\A\d+\z/;
  $timestamp = POSIX::strftime('%Y-%m-%d %H:%M:%S', gmtime($epoch));
} else {
  $timestamp = first_line($date_file);
  my @f = $timestamp =~ /\A(\d{4})-(\d\d)-(\d\d) (\d\d):(\d\d):(\d\d)\z/
    or die "$date_file: '$timestamp' is not 'YYYY-MM-DD HH:MM:SS'\n";
  # Reject impossible dates: the value must survive a round trip.
  my $epoch = eval { Time::Local::timegm_modern($f[5], $f[4], $f[3], $f[2], $f[1] - 1, $f[0]) };
  die "$date_file: '$timestamp' is not a valid date and time\n"
    unless defined $epoch && POSIX::strftime('%Y-%m-%d %H:%M:%S', gmtime($epoch)) eq $timestamp;
}

my $text = <<"END";
; Generated by tools/mkversion.pl from $version_file and $date_file -- do not edit.
VERSION_MAJOR = $major
VERSION_MINOR = $minor
VERSION_PATCH = $patch
.define VERSION_STRING "$version"
.define BUILD_TIMESTAMP "$timestamp"
END

# Keep the file (and its modification time) when nothing changed, so the
# rule can run on every build without forcing a rebuild.
if (-f $out_file) {
  open(my $old, '<', $out_file) or die "$out_file: $!\n";
  local $/;
  my $have = <$old> // '';
  close($old);
  exit 0 if $have eq $text;
}
my $tmp = "$out_file.tmp";
open(my $out, '>', $tmp) or die "$tmp: $!\n";
print {$out} $text;
close($out) or die "$tmp: $!\n";
rename($tmp, $out_file) or die "$out_file: $!\n";
